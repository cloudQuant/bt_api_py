"""Deterministic fictional calendar inputs for isolated simulation only.

These schedules, contracts, holidays and exceptions are invented.  They are
neither exchange data nor a complete instrument inventory.  The returned
review data is unverified and must never be used for account trading.
"""

import hashlib
import json
from copy import deepcopy
from datetime import date, timedelta

VENUES = ("SHFE", "INE", "DCE", "CZCE", "CFFEX", "GFEX")
SOURCE = {"id": "MOCK.simulation_only", "description": "MOCK fictional schedules; SIMULATION_ONLY"}
LABEL = {"data_origin": "MOCK", "environment": "SIMULATION_ONLY"}


def declared_publication_composite(composite, year):
    """Bind an origin only to the exact schedules generated by this module."""

    def canonical(value):
        return json.dumps(
            value, sort_keys=True, ensure_ascii=False, separators=(",", ":"), allow_nan=False
        ).encode("utf-8")

    data, _ = build(year)
    coverage = [
        {
            "venue": shard["venue"],
            "coverage_start": shard["coverage_start"],
            "coverage_end": shard["coverage_end"],
            "semantics": "DECLARED_INCLUSIVE",
        }
        for shard in sorted(data["shards"], key=lambda item: item["venue"])
    ]
    for changed in (False, True):
        if changed:
            for shard in data["shards"]:
                future = next(
                    row for row in shard["layers"]["trading_hours"] if row["kind"] == "future"
                )
                next(window for window in future["day_windows"] if window["id"] == "afternoon")[
                    "end"
                ] = "14:30"
        expected = {
            layer: sorted(
                (row for shard in data["shards"] for row in shard["layers"][layer]),
                key=canonical,
            )
            for layer in ("trading_days", "trading_hours", "exceptions")
        }
        expected["sources"] = [SOURCE.copy()]
        # Supplement derivation orders day windows by ID for affected venues.
        # Accept that lossless normalization while comparing every window field.
        observed = deepcopy(composite["snapshot"])
        for snapshot in (observed, expected):
            for row in snapshot["trading_hours"]:
                row["day_windows"] = sorted(row["day_windows"], key=canonical)
        if observed == expected and composite["manifest"]["coverage"] == coverage:
            manifest = {
                "schema": "bt_api.calendar-simulation-coverage/2",
                "snapshot_sha256": composite["snapshot_sha256"],
                "coverage": coverage,
                "data_origin": "SYNTHETIC_MOCK",
            }
            manifest_sha256 = hashlib.sha256(canonical(manifest)).hexdigest()
            binding = {
                "schema": "bt_api.calendar-simulation-binding/1",
                "snapshot_sha256": composite["snapshot_sha256"],
                "manifest_sha256": manifest_sha256,
            }
            return {
                **composite,
                "manifest": manifest,
                "manifest_sha256": manifest_sha256,
                "binding": binding,
                "binding_sha256": hashlib.sha256(canonical(binding)).hexdigest(),
            }
    return composite


def build(year):
    """Return a /2 review input and a small matching supplement for two years."""
    if type(year) is not int or not 1901 <= year <= 9998:
        raise ValueError("invalid year")
    first, last = date(year, 1, 1), date(year + 1, 12, 31)
    dates = [first + timedelta(days=n) for n in range((last - first).days + 1)]
    # Invented holiday deliberately has no relationship to exchange holidays.
    holidays = {date(y, 1, 15) for y in (year, year + 1)}
    is_open = lambda day: day.weekday() < 5 and day not in holidays  # noqa: E731
    exception_day = next(day for day in dates if day.month == 3 and is_open(day))
    shards = []
    for venue in VENUES:
        layers = {
            "sources": [SOURCE.copy()],
            "trading_days": [],
            "trading_hours": [],
            "exceptions": [],
        }
        layers["trading_days"] = [
            {
                "venue": venue,
                "day": day.isoformat(),
                "status": "open" if is_open(day) else "closed",
                "source_ids": [SOURCE["id"]],
            }
            for day in dates
        ]
        requirements = []
        for kind in ("future", "option"):
            product = "mock_future" if kind == "future" else "mock_option"
            contract = f"mock_{venue.lower()}_{kind}_contract"
            windows = [
                {
                    "id": "day_am",
                    "phase": "continuous",
                    "start": "09:00",
                    "end": "10:15",
                    "end_day_offset": 0,
                },
                {
                    "id": "day_pm",
                    "phase": "continuous",
                    "start": "10:30",
                    "end": "11:30" if kind == "future" else "11:00",
                    "end_day_offset": 0,
                },
                {
                    "id": "afternoon",
                    "phase": "continuous",
                    "start": "13:30",
                    "end": "15:00" if kind == "future" else "14:45",
                    "end_day_offset": 0,
                },
            ]
            night = [
                {
                    "id": "night",
                    "phase": "continuous",
                    "start": "21:00",
                    "end": "01:00" if kind == "future" else "23:00",
                    "end_day_offset": 1 if kind == "future" else 0,
                }
            ]
            mappings = []
            for day in dates:
                if is_open(day):
                    # Fictional Friday-night ownership is explicit for an ordinary
                    # Monday; a holiday in the gap suppresses the night session.
                    previous_open = day - timedelta(days=3 if day.weekday() == 0 else 1)
                    gap = [
                        previous_open + timedelta(days=n)
                        for n in range(1, (day - previous_open).days)
                    ]
                    local = (
                        previous_open.isoformat()
                        if previous_open >= first
                        and is_open(previous_open)
                        and not any(item in holidays for item in gap)
                        else None
                    )
                    mappings.append(
                        {
                            "trading_day": day.isoformat(),
                            "start_date": local,
                            "source_ids": [SOURCE["id"]],
                        }
                    )
            layers["trading_hours"].append(
                {
                    "venue": venue,
                    "kind": kind,
                    "product": product,
                    "contracts": [contract],
                    "valid_from": first.isoformat(),
                    "valid_to": last.isoformat(),
                    "day_windows": windows,
                    "night_windows": night,
                    "night_mappings": mappings,
                    "windows_complete": True,
                    "exceptions_complete": True,
                    "source_ids": [SOURCE["id"]],
                }
            )
            requirements.append(
                {
                    "kind": kind,
                    "product": product,
                    "contract": contract,
                    "start_day": first.isoformat(),
                    "end_day": last.isoformat(),
                }
            )
            layers["exceptions"].append(
                {
                    "venue": venue,
                    "kind": kind,
                    "product": product,
                    "contract": contract if kind == "future" else None,
                    "trading_day": exception_day.isoformat(),
                    "action": "close_day" if kind == "future" else "cancel_window",
                    "window_id": None if kind == "future" else "day_pm",
                    "source_ids": [SOURCE["id"]],
                }
            )
        shards.append(
            {
                "venue": venue,
                "coverage_start": first.isoformat(),
                "coverage_end": last.isoformat(),
                "layers": layers,
                "requirements": requirements,
                "unresolved": [],
            }
        )
    supplement = {
        "sources": [SOURCE.copy()],
        "trading_days": [shards[0]["layers"]["trading_days"][0].copy()],
        "trading_hours": [],
        "exceptions": [],
    }
    return {
        "shards": shards,
        "source_texts": {SOURCE["id"]: "MOCK fictional data; SIMULATION_ONLY; not venue evidence"},
        "metadata": LABEL.copy(),
    }, supplement
